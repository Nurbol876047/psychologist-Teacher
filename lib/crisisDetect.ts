import { normalize } from "@/lib/matchTopic";

// Дағдарыс белгілері: өзіне зиян келтіру, суицид ойлары, зорлық-зомбылық.
// Тізімді толық деп есептемеңіз — күмән туындаса, жауапты жіберер алдында осы
// сөздерді толықтырыңыз.
const CRISIS_PATTERNS: string[] = [
  "өзімді өлтіргім",
  "өмір сүргім келмейді",
  "өмірімнің мәні жоқ",
  "өзіме зиян",
  "асылғым келеді",
  "жоғалғым келеді",
  "суицид",
  "өзімді жоямын",
  "боп өлгім келеді",

  "покончить с собой",
  "не хочу жить",
  "хочу умереть",
  "причинить себе вред",
  "нанести себе вред",
  "самоубийство",
  "убить себя",
  "суицид",
  "жизнь не имеет смысла",
];

export function isCrisisMessage(message: string): boolean {
  const normalized = normalize(message);
  return CRISIS_PATTERNS.some((pattern) => normalized.includes(normalize(pattern)));
}
